"""Allocate one immutable application identity; startup never calls this file."""
from datetime import datetime
from pathlib import Path
import argparse
import json
import os
import re
import tempfile


def atomic_text(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=path.name + '.', suffix='.tmp', dir=path.parent)
    try:
        with os.fdopen(fd, 'w', encoding='utf-8', newline='\n') as stream:
            stream.write(text)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def next_version(raw):
    match = re.fullmatch(r'([0-9])\.([0-9])\.([0-9])\.([0-9]{3})', raw)
    if not match:
        raise ValueError('Invalid VERSION; original identity preserved')
    major, minor, patch, revision = map(int, match.groups())
    revision += 1
    if revision > 999:
        revision, patch = 1, patch + 1
    if patch > 9:
        patch, minor = 0, minor + 1
    if minor > 9:
        minor, major = 0, major + 1
    if major > 9:
        raise ValueError('Version overflow; original identity preserved')
    return f'{major}.{minor}.{patch}.{revision:03d}'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--module', default='src/build_info.py')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    module = (root / args.module).resolve()
    if root not in module.parents or module.suffix != '.py':
        raise ValueError('Build-info module must stay inside this project')
    owner = root / 'VERSION'
    version = next_version(owner.read_text(encoding='utf-8-sig').strip())
    stamp = datetime.now().astimezone().replace(microsecond=0)
    label = f'v{version} | BUILD {stamp:%Y-%m-%d %H:%M:%S}'
    # Consume the identity before generating its derivatives; failed builds may
    # consume a number but cannot silently reuse a previously prepared identity.
    atomic_text(owner, version + '\n')
    fields = {'BUILD_VERSION': version, 'BUILD_NUMBER': version.rsplit('.', 1)[1],
              'BUILD_DATETIME': stamp.isoformat(), 'BUILD_LABEL': label}
    atomic_text(module, '# Generated by scripts/prepare_build_identity.py.\n' +
                '\n'.join(f'{key} = {value!r}' for key, value in fields.items()) + '\n')
    numeric = ', '.join(str(int(v)) for v in version.split('.'))
    strings = ',\n'.join(f'          StringStruct({json.dumps(key)}, {json.dumps(value)})' for key, value in
                         [('FileVersion', version), ('ProductVersion', version), ('BuildDateTime', stamp.isoformat())])
    resource = ('VSVersionInfo(ffi=FixedFileInfo(filevers=(' + numeric + '), prodvers=(' + numeric +
                '), mask=0x3f, flags=0, OS=0x40004, fileType=1, subtype=0, date=(0, 0)),\n' +
                ' kids=[StringFileInfo([StringTable("040904B0", [\n' + strings +
                '\n ])]), VarFileInfo([VarStruct("Translation", [1033, 1200])])])\n')
    atomic_text(root / 'scripts/build/version_info.generated.txt', resource)
    print(label)


if __name__ == '__main__':
    main()
